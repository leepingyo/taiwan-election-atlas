import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
for(const file of ['index.html','embed.html']){
 const html=await readFile(new URL('../public/'+file,import.meta.url),'utf8');
 const app=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)][0][1];
 const data=html.match(/<script id="map-data" type="application\/json">([\s\S]*?)<\/script>/)[1];
 const elements=new Map(['map-data','preset','detail','heading','panel-kicker','subheading'].map(id=>[id,{textContent:id==='map-data'?data:id==='preset'?'{}':'',innerHTML:'',querySelectorAll:()=>[]} ]));
 const context=vm.createContext({document:{documentElement:{classList:{add(){}}},addEventListener(){},getElementById:id=>elements.get(id)||null},location:{pathname:'/'+file,search:''},URLSearchParams,localStorage:{getItem:()=>null}});
 vm.runInContext(app.slice(0,app.indexOf('function navigate('))+app.slice(app.indexOf('const mayorPortrait ='),app.indexOf('function districtButtons('))+app.slice(app.indexOf('function renderDetail(){'),app.indexOf('function render(){')),context);
 vm.runInContext('renderDetail()',context);
 assert.equal((elements.get('detail').innerHTML.match(/data-c="/g)||[]).length,22,file+' national county list');
 assert.ok(elements.get('detail').innerHTML.includes('蔣萬安'),file+' candidate names');
 vm.runInContext("county='臺北市';tab='mayor';renderDetail()",context);
 assert.ok(elements.get('detail').innerHTML.includes('蔣萬安'),file+' mayor list');
 assert.equal((elements.get('detail').innerHTML.match(/class="candidate-portrait"/g)||[]).length,6);
 vm.runInContext("county='連江縣';tab='townMayor';renderDetail()",context);
 assert.ok(elements.get('detail').innerHTML.includes('東引鄉'),file+' township list');
 vm.runInContext("county='臺北市';tab='council';renderDetail()",context);
 assert.ok(elements.get('detail').innerHTML.includes('第 1 選區'),file+' council list');
 vm.runInContext("county='';settings.colors['county|臺北市|']='blue';liveResults['臺北市']={mayor:[['郭璽','台灣麻將最大黨',10,false],['蔣萬安','中國國民黨',900,false],['沈伯洋','民主進步黨',1200,false]]};renderDetail()",context);
 assert.equal(vm.runInContext("fill('county','臺北市')",context),'var(--green)',file+' current leader overrides old manual color');
 let card=elements.get('detail').innerHTML.match(/data-c="臺北市"[\s\S]*?<\/button>/)[0];
 assert.ok(card.indexOf('沈伯洋')<card.indexOf('蔣萬安'));assert.ok(!card.includes('郭璽'));assert.ok(card.includes('1,200 票')&&card.includes('900 票'));
 vm.runInContext("liveResults['臺北市'].mayor[1][2]=1500;renderDetail()",context);
 assert.equal(vm.runInContext("fill('county','臺北市')",context),'var(--blue)',file+' lead changes update color');
 vm.runInContext("liveResults['臺北市'].mayor[2][2]=1500;renderDetail()",context);
 assert.equal(vm.runInContext("fill('county','臺北市')",context),'var(--empty)',file+' tie stays neutral');
 assert.ok(elements.get('detail').innerHTML.includes('同票領先'));
 vm.runInContext("liveResults['臺北市'].mayor.forEach(r=>r[2]=0);renderDetail()",context);
 assert.equal(vm.runInContext("fill('county','臺北市')",context),'var(--empty)',file+' zero totals do not create a leader');
 vm.runInContext("liveResults['臺北市'].mayorByTown={'松山區':[['蔣萬安','中國國民黨',5,false],['沈伯洋','民主進步黨',8,false]]}",context);
 assert.equal(vm.runInContext("fill('town','臺北市','松山區')",context),'var(--green)',file+' township uses its own mayor counts');
 vm.runInContext("county='';officialCountingStage='prior';renderDetail()",context);
 assert.ok(elements.get('detail').innerHTML.includes('開票進度：尚未開票'));
 vm.runInContext("officialCountingStage='count';officialNationalProgress={completed:1250,total:2000,percent:62.5};renderDetail()",context);
 assert.ok(elements.get('detail').innerHTML.includes('62.50%（1,250／2,000 所）'));
 vm.runInContext("county='臺北市';tab='mayor';officialProgressByCounty={};renderDetail()",context);
 assert.ok(elements.get('detail').innerHTML.includes('官方尚未提供此縣市開票百分比'));
 assert.ok(elements.get('detail').innerHTML.includes('每 30 秒檢查更新'));
 console.log('PASS '+file+': national list, mayor names/portraits, township mayors and council render');
}
